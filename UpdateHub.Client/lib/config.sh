#!/usr/bin/env bash
# Чтение и проверка настроек.

# Значения по умолчанию.
#
# Заданы здесь, а не в файле настроек: файл на машине правят руками, и всё,
# что в нём не написано, обязано иметь разумное значение.
UH_CONFIG_FILE="${UH_CONFIG_FILE:-/etc/updatehub/updatehub.conf}"

SERVER_URL=""
DATA_DIR="/home/data"
TEMP_DIR="/var/tmp/updatehub"
STATE_DIR="/var/lib/updatehub"
CLIENT_ID_FILE="/etc/updatehub/client-id"
LOG_FILE="/var/log/updatehub.log"
USERNAME=""
PASSWORD=""

# Запас свободного места сверх объёма загрузки, в мегабайтах.
#
# Файлы сначала складываются во временный каталог целиком и лишь потом
# переносятся в рабочую папку. Без запаса загрузка шестигигабайтного образа
# заполнила бы диск под ноль и оставила машину неработоспособной.
FREE_SPACE_MARGIN_MB="512"

# Сколько раз повторять оборвавшуюся загрузку файла.
#
# Отдача шести гигабайт по каналу 2 Мбит/с идёт около семи часов, и обрыв
# на такой дистанции — обычное дело, а не исключительная ситуация.
DOWNLOAD_RETRIES="10"

# Пауза между повторами, в секундах.
DOWNLOAD_RETRY_DELAY="30"

# Ограничение скорости загрузки, в формате curl (например 512k). Пусто — без ограничения.
DOWNLOAD_RATE_LIMIT=""

# Время ожидания ответа на служебные запросы, в секундах.
#
# К загрузке файлов не относится: она идёт часами и своего ограничения не имеет.
REQUEST_TIMEOUT="60"

# Читает файл настроек.
#
# Файл подключается через source, то есть это обычный сценарий оболочки.
# Формат выбран ради человека, который будет править его на машине без
# интернета: ни YAML, ни JSON там разбирать нечем.
load_config() {
    if [ ! -f "$UH_CONFIG_FILE" ]; then
        die "Файл настроек не найден: $UH_CONFIG_FILE. Скопируйте updatehub.conf.example и заполните его"
    fi

    # shellcheck disable=SC1090
    . "$UH_CONFIG_FILE"

    UH_LOG_FILE="$LOG_FILE"
}

# Проверяет, что настроек достаточно для работы.
validate_config() {
    [ -n "$SERVER_URL" ] || die "В настройках не задан SERVER_URL"

    case "$SERVER_URL" in
        http://* | https://*) ;;
        *) die "SERVER_URL должен начинаться с http:// или https://, сейчас: $SERVER_URL" ;;
    esac

    # Замыкающая косая черта в адресе привела бы к двойной черте в запросах.
    SERVER_URL="${SERVER_URL%/}"

    [ -n "$DATA_DIR" ] || die "В настройках не задан DATA_DIR"
    [ -n "$TEMP_DIR" ] || die "В настройках не задан TEMP_DIR"
    [ -n "$STATE_DIR" ] || die "В настройках не задан STATE_DIR"

    case "$DATA_DIR" in
        /) die "DATA_DIR не может быть корнем файловой системы" ;;
        /*) ;;
        *) die "DATA_DIR должен быть абсолютным путём, сейчас: $DATA_DIR" ;;
    esac

    # Временный каталог полностью очищается после переноса файлов, поэтому
    # совпадение с рабочей папкой означало бы удаление всех обновлений.
    if [ "$TEMP_DIR" = "$DATA_DIR" ]; then
        die "TEMP_DIR не может совпадать с DATA_DIR: временный каталог очищается целиком"
    fi

    case "$TEMP_DIR" in
        "$DATA_DIR"/*) die "TEMP_DIR не может находиться внутри DATA_DIR: он очищается целиком" ;;
    esac
}
