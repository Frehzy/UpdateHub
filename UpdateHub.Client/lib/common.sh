#!/usr/bin/env bash
# Общие подпрограммы: журнал, проверки окружения, разбор текстовых ответов.
#
# Файл только подключается через source и сам ничего не делает.

# Уровень подробности журнала: 0 — только ошибки, 1 — обычный, 2 — с подробностями.
UH_VERBOSITY="${UH_VERBOSITY:-1}"

# Пишет строку в журнал.
#
# Всё уходит в поток ошибок, а не в стандартный вывод: подпрограммы возвращают
# результат печатью, и строка журнала, попавшая в вывод, испортила бы его.
# Аргументы: $1 — метка уровня, далее — текст сообщения.
log_write() {
    local level="$1"
    shift
    local moment
    moment="$(date '+%Y-%m-%d %H:%M:%S')"

    printf '%s [%s] %s\n' "$moment" "$level" "$*" >&2

    if [ -n "${UH_LOG_FILE:-}" ]; then
        printf '%s [%s] %s\n' "$moment" "$level" "$*" >>"$UH_LOG_FILE" 2>/dev/null || true
    fi
}

# Обычное сообщение о ходе работы.
log_info() {
    [ "$UH_VERBOSITY" -ge 1 ] && log_write "инфо" "$@"
    return 0
}

# Подробность, нужная при разборе неполадок.
log_debug() {
    [ "$UH_VERBOSITY" -ge 2 ] && log_write "отладка" "$@"
    return 0
}

# Предупреждение: работа продолжается.
log_warn() {
    log_write "ВНИМАНИЕ" "$@"
}

# Ошибка: работа продолжается или прерывается вызывающим.
log_error() {
    log_write "ОШИБКА" "$@"
}

# Печатает сообщение и завершает работу с ненулевым кодом.
#
# Код возврата берётся из переменной UH_EXIT_CODE, если она задана: так
# вызывающая сторона различает «нет связи» и «неверные учётные данные»,
# а systemd — временный сбой и настроечную ошибку.
die() {
    log_error "$@"
    exit "${UH_EXIT_CODE:-1}"
}

# Проверяет наличие внешней команды.
# Аргументы: $1 — имя команды, $2 — пакет, в котором она находится.
require_command() {
    local name="$1" package="${2:-}"

    if ! command -v "$name" >/dev/null 2>&1; then
        if [ -n "$package" ]; then
            die "Не найдена команда '$name'. Установите пакет $package"
        fi
        die "Не найдена команда '$name'"
    fi
}

# Создаёт каталог вместе с родительскими.
ensure_dir() {
    local path="$1"
    [ -d "$path" ] && return 0

    mkdir -p "$path" || die "Не удалось создать каталог: $path"
}

# Достаёт значение из ответа вида «ключ=значение».
#
# Разделяет по первому знаку равенства: сообщения об ошибках пишет человек,
# и знак равенства внутри текста встречается.
# Аргументы: $1 — текст ответа, $2 — искомый ключ.
text_pair_value() {
    local text="$1" key="$2"

    printf '%s\n' "$text" | while IFS= read -r line; do
        case "$line" in
            "$key="*)
                printf '%s\n' "${line#*=}"
                break
                ;;
        esac
    done
}

# Достаёт сообщение об ошибке из текстового ответа сервера.
# Аргументы: $1 — текст ответа, $2 — что вернуть при отсутствии сообщения.
text_error_message() {
    local text="$1" fallback="$2" message

    message="$(text_pair_value "$text" "error")"
    if [ -n "$message" ]; then
        printf '%s\n' "$message"
    else
        printf '%s\n' "$fallback"
    fi
}

# Переводит размер в байтах в удобные для чтения единицы.
human_size() {
    local bytes="${1:-0}"

    awk -v value="$bytes" 'BEGIN {
        split("Б КБ МБ ГБ ТБ", units, " ")
        unit = 1
        while (value >= 1024 && unit < 5) {
            value /= 1024
            unit++
        }
        if (unit == 1) {
            printf "%d %s\n", value, units[unit]
        } else {
            printf "%.1f %s\n", value, units[unit]
        }
    }'
}

# Возвращает свободное место в байтах на файловой системе указанного каталога.
#
# Берётся именно каталог, а не путь к файлу: файла может ещё не быть,
# а df по несуществующему пути завершается ошибкой.
free_space_bytes() {
    local dir="$1"

    while [ ! -d "$dir" ] && [ "$dir" != "/" ]; do
        dir="$(dirname "$dir")"
    done

    df -Pk "$dir" 2>/dev/null | awk 'NR == 2 { printf "%.0f\n", $4 * 1024 }'
}

# Проверяет, что путь относительный и не выходит за пределы своего каталога.
#
# Путь приходит от сервера и подставляется в обращение к файловой системе.
# Сервер такие пути и сам отклоняет, но проверка на стороне клиента стоит
# двух строк, а её отсутствие означает запись куда угодно от имени root.
# Аргументы: $1 — проверяемый путь.
is_safe_relative_path() {
    local path="$1"

    case "$path" in
        "" | /* | *$'\n'* ) return 1 ;;
        .. | ../* | */../* | */.. ) return 1 ;;
    esac

    return 0
}
