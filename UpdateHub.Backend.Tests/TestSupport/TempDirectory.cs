using Microsoft.Data.Sqlite;

namespace UpdateHub.Backend.Tests.TestSupport;

/// <summary>
/// Уборка временных каталогов после теста.
/// </summary>
/// <remarks>
/// Вынесено отдельно, потому что нужно в двух местах и оба раза упирается
/// в одно и то же. Microsoft.Data.Sqlite держит соединения в пуле: после
/// <c>Dispose</c> контекста соединение возвращается в пул, но не закрывается,
/// и дескриптор файла базы остаётся открытым.
/// <para>
/// В Linux открытый файл удаляется без возражений, поэтому сборка по коммитам
/// такую беду не покажет. В Windows каталог с открытым файлом удалить нельзя,
/// и уборка падает с <see cref="IOException"/> уже после того, как проверка
/// прошла — тест выглядит неудачным из-за собственного <c>Dispose</c>.
/// </para>
/// </remarks>
public static class TempDirectory
{
    /// <summary>
    /// Удаляет каталог со всем содержимым, освободив файлы базы.
    /// </summary>
    /// <param name="path">Каталог; отсутствующий считается уже убранным.</param>
    /// <remarks>
    /// Неудача уборки намеренно не приводит к отказу теста. Временный каталог —
    /// не предмет проверки, а исключение из <c>Dispose</c> подменило бы итог
    /// на ошибку и скрыло настоящий результат. Каталог лежит в TEMP, и его
    /// уберёт система.
    /// </remarks>
    public static void Remove(string path)
    {
        // Закрывает соединения, лежащие в пуле, и вместе с ними — файлы базы.
        // Открытые соединения при этом не затрагиваются: базы в памяти,
        // которые держат тесты, продолжают жить.
        SqliteConnection.ClearAllPools();

        try
        {
            if (Directory.Exists(path))
            {
                Directory.Delete(path, recursive: true);
            }
        }
        catch (IOException)
        {
            // Файл всё ещё занят — каталог останется в TEMP.
        }
        catch (UnauthorizedAccessException)
        {
            // Нет прав на удаление — то же самое.
        }
    }
}
